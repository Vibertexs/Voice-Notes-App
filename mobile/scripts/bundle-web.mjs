/**
 * Inlines the Vite build into a single JS module the app can hand to a WebView.
 *
 * Loading the build as separate asset files means fighting file:// origin rules
 * on Android and asset resolution on both platforms. One self-contained HTML
 * string sidesteps all of it, and at ~310KB it is small next to the JS bundle
 * it ships inside.
 *
 * Run: node scripts/bundle-web.mjs   (from mobile/)
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, '..', '..', 'frontend-dist');
const out = join(here, '..', 'src', 'webapp.generated.js');

const assets = readdirSync(join(dist, 'assets'));
const jsName = assets.find((f) => f.endsWith('.js'));
const cssName = assets.find((f) => f.endsWith('.css'));
if (!jsName || !cssName) throw new Error('frontend-dist/assets is missing a js or css file. Run `npm run build` at the repo root first.');

const js = readFileSync(join(dist, 'assets', jsName), 'utf8');
const css = readFileSync(join(dist, 'assets', cssName), 'utf8');

// The page is assembled rather than taken from dist/index.html because the
// script and stylesheet have to become inline tags, and the viewport needs
// to be pinned for a phone.
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, maximum-scale=1, user-scalable=no" />
<title>Class Notes</title>
<style>
${css}
/* Native shell adjustments: the WebView has no browser chrome, and a phone
   needs the safe-area inset the browser would otherwise provide. */
html, body { overscroll-behavior: none; }
body { padding-top: env(safe-area-inset-top); padding-bottom: env(safe-area-inset-bottom); }
* { -webkit-tap-highlight-color: transparent; }
input, textarea { font-size: 16px; } /* stops iOS zooming the page on focus */
</style>
</head>
<body>
<div id="root"></div>
<script type="module">
${js}
</script>
</body>
</html>`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  '// GENERATED by scripts/bundle-web.mjs - do not edit.\n'
  + '// Source: frontend-dist/, built from frontend/ by `npm run build` at the repo root.\n'
  + `export const WEB_APP_HTML = ${JSON.stringify(html)};\n`,
  'utf8',
);

const kb = (n) => `${Math.round(n / 1024)}KB`;
console.log(`webapp.generated.js written: html ${kb(html.length)} (js ${kb(js.length)}, css ${kb(css.length)})`);
